/** 課程活動報名 — 個資蒐集告知聲明（依 APP 個資聲明.docx） */
export function buildPrivacyStatement(brandName: string): string {
  return [
    '【個人資料蒐集告知聲明】',
    '',
    `${brandName}（以下簡稱本單位）為了辦理課程活動業務，依據《個人資料保護法》規定，向您告知下列事項：`,
    '',
    '蒐集之目的：作為本次活動之報名聯繫、身份確認、保險辦理及後續相關通知之用（特定目的代號：090 消費者、客戶管理與服務；158 學生（員）管理等）。',
    '',
    '蒐集之個人資料類別：姓名、電話、小組及其他報名所必要之資料。',
    '',
    '利用期間、地區、對象及方式：',
    '期間：自報名起至本次活動結束後六個月內（或依法律規定保存期限）。',
    '地區：台灣地區。',
    '對象：本單位及因執行業務必要之相關協辦／保險單位。',
    '方式：以數位檔案或紙本形式進行必要之處理與利用。',
    '',
    '您的權利（個資法第3條）：您可向本單位行使查詢、閱覽、補充、更正、要求停止蒐集／處理／利用或刪除之權利。',
    '',
    '自由提供與影響：您可自由選擇是否提供個人資料，若拒絕提供或提供不全，本單位將無法受理您的報名或提供完整服務。',
  ].join('\n');
}

